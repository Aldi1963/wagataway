type Dict = typeof id;

// Kamus bahasa Inggris dipisah ke chunk sendiri (./i18n-en) agar tidak
// membebani bundle awal — hanya diunduh saat user memilih English.
let enDict: Dict | null = null;
let enLoading: Promise<Dict> | null = null;
function loadEnDict(): Promise<Dict> {
  if (enDict) return Promise.resolve(enDict);
  if (!enLoading) {
    enLoading = import("./i18n-en").then((m) => {
      enDict = (m.default || m) as Dict;
      return enDict;
    });
  }
  return enLoading;
}

const STORAGE_KEY = "wagataway-lang";

function resolve(dict: Dict, key: string): string {
  const parts = key.split(".");
  let cur: unknown = dict;
  for (const p of parts) {
    if (cur && typeof cur === "object" && p in (cur as Record<string, unknown>)) {
      cur = (cur as Record<string, unknown>)[p];
    } else {
      return key;
    }
  }
  return typeof cur === "string" ? cur : key;
}

interface LangContextType {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
}

const LangContext = createContext<LangContextType | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const stored = localStorage.getItem(STORAGE_KEY);
    return stored === "en" || stored === "id" ? stored : "id";
  });
  // Versi kamus en yang sudah ter-load; naik tiap selesai load agar t() re-render.
  const [enVer, setEnVer] = useState(0);

  useEffect(() => {
    document.documentElement.lang = lang;
    localStorage.setItem(STORAGE_KEY, lang);
    if (lang === "en" && !enDict) {
      loadEnDict().then(() => setEnVer((v) => v + 1));
    }
  }, [lang]);

  const setLang = (l: Lang) => setLangState(l);
  // Selama kamus en belum datang, fallback ke id (tidak blank).
  const t = (key: string) => resolve(lang === "en" && enDict ? enDict : id, key);
  void enVer;

  return (
    <LangContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LangContext.Provider>
  );
}

export function useLang(): LangContextType {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error("useLang harus dipakai di dalam LanguageProvider");
  return ctx;
}

/** Kamus sinkron untuk kebutuhan non-React (fallback id bila en belum ter-load). */
export function getDictSync(lang: Lang): Dict {
  return lang === "en" && enDict ? enDict : id;
}

/** "5 menit lalu" / "5 min ago" sesuai bahasa aktif. */
export function timeAgo(iso: string, lang: Lang): string {
  const d = getDictSync(lang).notifications;
  const diff = Date.now() - new Date(iso).getTime();
  const mins = Math.floor(diff / 60000);
  if (mins < 1) return d.justNow;
  if (mins < 60) return `${mins} ${d.minAgo}`;
  const hours = Math.floor(mins / 60);
  if (hours < 24) return `${hours} ${d.hourAgo}`;
  const days = Math.floor(hours / 24);
  if (days < 30) return `${days} ${d.dayAgo}`;
  return new Date(iso).toLocaleDateString(lang === "id" ? "id-ID" : "en-US");
}
